import argparse
import csv
from pathlib import Path

import matplotlib.pyplot as plt


REPLICA_ORDER = [1, 4, 7, 10]
STYLES = {
    1: {"marker": "s", "color": "#8a2be2", "linestyle": "-"},
    4: {"marker": "s", "color": "#00a878", "linestyle": "--"},
    7: {"marker": "^", "color": "#56b4e9", "linestyle": "-."},
    10: {"marker": "o", "color": "#e69f00", "linestyle": ":"},
}


plt.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
    "mathtext.fontset": "stix",
    "pdf.fonttype": 42,
    "ps.fonttype": 42,
    "axes.labelsize": 17,
    "axes.titlesize": 17,
    "xtick.labelsize": 16,
    "ytick.labelsize": 16,
    "legend.fontsize": 16,
    "axes.linewidth": 1.0,
})


def default_csv_path(bandwidth):
    script_dir = Path(__file__).resolve().parent
    safe = "".join(ch if ch.isalnum() or ch in "_-" else "_" for ch in bandwidth)
    return script_dir / "benchmark_results" / f"MVPMultiServer_{safe}_results.csv"


def read_rows(csv_path):
    rows = []
    with csv_path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            if row.get("status") != "OK":
                continue
            rows.append({
                "replicas": int(row["replicas"]),
                "clients": int(row["clients"]),
                "throughput": float(row["throughputOpsPerSec"]),
                "latency": float(row["latencyMs"]),
            })
    return rows


def plot(rows, output):
    fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.55))
    all_clients = sorted({row["clients"] for row in rows})

    for replicas in REPLICA_ORDER:
        series = sorted(
            [row for row in rows if row["replicas"] == replicas],
            key=lambda row: row["clients"],
        )
        if not series:
            continue
        xs = [row["clients"] for row in series]
        throughput = [row["throughput"] for row in series]
        latency = [row["latency"] for row in series]
        style = STYLES[replicas]
        label = f"n = {replicas}"

        for ax, ys in ((axes[0], throughput), (axes[1], latency)):
            ax.plot(
                xs,
                ys,
                color=style["color"],
                linestyle=style["linestyle"],
                linewidth=1.8,
                marker=style["marker"],
                markersize=6.8,
                markerfacecolor=style["color"],
                markeredgecolor=style["color"],
                markeredgewidth=1.0,
                label=label,
            )

    axes[0].set_xlabel(r"$\#$ Clients")
    axes[0].set_ylabel("Throughput (ops/s)")
    axes[0].set_xticks(all_clients)
    axes[0].set_ylim(bottom=0)
    axes[0].grid(True, linestyle=":", linewidth=0.75, alpha=0.7)

    axes[1].set_xlabel(r"$\#$ Clients")
    axes[1].set_ylabel("Latency (ms)")
    axes[1].set_xticks(all_clients)
    axes[1].set_ylim(bottom=0)
    axes[1].grid(True, linestyle=":", linewidth=0.75, alpha=0.7)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        ncol=4,
        frameon=False,
        bbox_to_anchor=(0.5, 1.04),
        handlelength=2.4,
        columnspacing=1.4,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.93), w_pad=2.1)
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", nargs="?", help="CSV generated by run_mvp_multiserver_docker_benchmark.sh")
    parser.add_argument("--bandwidth", default="10gbit", help="Bandwidth label for default CSV name")
    parser.add_argument("--out", default=None, help="Output PDF path")
    args = parser.parse_args()

    csv_path = Path(args.csv).resolve() if args.csv else default_csv_path(args.bandwidth).resolve()
    output = Path(args.out) if args.out else csv_path.parent / f"MVPMultiServer_{args.bandwidth}_performance.pdf"
    if not output.is_absolute():
        output = Path.cwd() / output

    rows = read_rows(csv_path)
    if not rows:
        raise ValueError(f"No OK rows found in {csv_path}")
    plot(rows, output)
    print(f"Read {csv_path}")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
